#!/usr/bin/env python3
"""Generate vectors.h from the base project's Python implementation
(sinise/autoterm-heater-control), so the C port is checked byte-for-byte against it.

usage: gen_vectors.py <path to base autoterm/ directory> > vectors.h
"""
import importlib.util, sys

base = sys.argv[1]
def load(name):
    spec = importlib.util.spec_from_file_location(name, f"{base}/{name}.py")
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m

proto = load("autoterm_protocol")
sys.path.insert(0, base)
src = open(f"{base}/autoterm_addon.py").read()
# pull only the pure helpers out of the add-on (it imports paho/serial at top)
ns = {"crc_bytes": proto.crc_bytes}
start = src.index("def build_frame(")
end = src.index("def _iso(ts)")
exec(src[start:end], {**ns, "STATE_NAMES": {0:"idle",2:"running",3:"late-run",4:"cooldown",5:"final-shutdown"}, "__builtins__": __builtins__}, ns)
build_frame, build_pubr0 = ns["build_frame"], ns["build_pubr0_frame"]

def arr(name, b):
    print(f"static const uint8_t {name}[] = {{" + ", ".join(f"0x{x:02x}" for x in b) + "};")

print("/* generated by gen_vectors.py from the base project, do not edit */")
arr("V_START_THERMOSTAT", build_frame(3, 1, bytes([0, 0x22])))
arr("V_START_PREHEAT", build_frame(3, 1, bytes([0, 0x1E])))
arr("V_PREHEAT_TIME_90", build_frame(3, 2, (90).to_bytes(2, "big")))
arr("V_STOP", build_frame(3, 3))
arr("V_PUMP", build_frame(3, 0x21, bytes([0, 0x28])))
arr("V_PUBR0", build_pubr0())
status = bytes([2, 3, 78, 50, 52, 0, 0, 40, 0, 12, 0, 33, 0xFF, 0, 0, 0, 5, 0])
arr("V_STATUS_REPLY", build_frame(4, 0x0F, status))
arr("V_STATUS_PAYLOAD", status)

# extended frame sample + expected decode (base project's decode_extended_payload)
spec = importlib.util.spec_from_file_location("addon_src", f"{base}/autoterm_addon.py")
import types, re
mod = types.ModuleType("addon_src")
mod.__dict__.update({"crc_bytes": proto.crc_bytes, "re": re, "_re": re})
pre = src[src.index("HEATER_PROFILES = {"):src.index("def build_frame(")]
exec("import re as _re\nSTATE_NAMES={}\n" + pre, mod.__dict__)
prof = mod.prepare_profile("autoterm_flow_5")
p = bytearray(58)
p[0], p[1] = 3, 2
p[2:5] = (1234).to_bytes(3, "big")
p[11], p[12], p[13], p[15] = 40, 39, 0, 32
p[17], p[18] = (212 + 273) >> 8, (212 + 273) & 255
p[19], p[20], p[21] = 61, 70, 33
p[22], p[23] = 0x00, 0x7d  # 12.5 V
p[36] = 25
p[52] = 1
p[54], p[55] = 0x01, 0x2c
arr("V_EXT_PAYLOAD", bytes(p))
d = mod.decode_extended_payload(bytes(p), prof)
print("/* expected: " + repr(d) + " */")
print(f"#define V_EXT_FLAME {d['ext_flame_temp_c']}")
print(f"#define V_EXT_VOLT {d['ext_voltage']}f")
print(f"#define V_EXT_PUMP {d['ext_fuel_pump_hz']}f")
print(f"#define V_EXT_PCT {int(d['ext_output_pct'])}")
print(f"#define V_EXT_MODE_CODE {d['ext_mode_code']}")
print(f'#define V_EXT_MODE_NAME "{d["ext_mode_name"]}"')
print(f'#define V_EXT_FAULT_NAME "{d["ext_fault_name"]}"')
# every mode name for state 0..4, substate 0..9
print("static const char *const V_MODES[44] = {" + ", ".join('"%s"' % n for n in prof["state_names"]) + "};")
print("static const char *const V_FAULTS[256] = {" + ", ".join(('"%s"' % prof["faults"][i]) if i in prof["faults"] else "0" for i in range(256)) + "};")
